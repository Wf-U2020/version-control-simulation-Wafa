#prompt the user for a word
word = input("Enter a word: ")

#print the length of the word
print(f"The length of the word '{word}' is: {len(word)}")

#print the word in uppercase
print(f"The word '{word}' in uppercase is: {word.upper()}")

#print the word repeated 3 times
print(f"The word '{word}' repeated 3 times is: {word * 3}")

